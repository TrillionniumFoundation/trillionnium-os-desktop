pub fn working_entry(
    candidate: &str,
    intent: &str,
    early: &str,
    returned: &str,
) -> io::Result<String> {
    entry(candidate)?;
    if ![intent, early, returned].into_iter().all(digest) {
        return Err(reject("working entry source commitment differs"));
    }
    let masks = original::PACKAGE_WRITERS
        .iter()
        .chain(original::SUSPEND_TARGETS.iter())
        .map(|s| format!(" systemd.mask={s}"))
        .collect::<String>();
    let args = format!(
        "root=UUID={} ro rootwait init=/usr/lib/droidloom/board-init lsm={LSM_ORDER} enforcing=1 selinux=1 audit=1 panic=10 systemd.wants=droidloom-working-qualification.service droidloom.working={intent} droidloom.working.config={early} droidloom.working.return={returned}{masks}",
        original::ROOT_UUID
    );
    Ok(format!(
        "\nmenuentry 'Droidloom working qualification' --id 'droidloom-working-qualification-{candidate}' {{\n  search --no-floppy --fs-uuid --set=root {}\n  linux /boot/droidloom/kernels/{}/vmlinuz {args}\n  initrd /boot/droidloom/working-qualification/{candidate}/initrd.img\n}}\n",
        original::ROOT_UUID,
        original::KERNEL_SHA
    ))
}
