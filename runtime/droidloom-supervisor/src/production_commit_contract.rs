fn reject(why: &str) -> io::Error {
    io::Error::new(io::ErrorKind::PermissionDenied, why)
}
pub fn digest(s: &str) -> bool {
    s.len() == 64
        && s.bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}
fn commit(s: &str) -> bool {
    s.len() == 40
        && s.bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct BytesPin {
    pub bytes: u64,
    pub sha256: String,
}
impl BytesPin {
    pub fn validate(&self, limit: u64) -> io::Result<()> {
        if self.bytes == 0 || self.bytes > limit || !digest(&self.sha256) {
            return Err(reject("production needs whole bounded normal bytes"));
        }
        Ok(())
    }
}
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Configuration {
    pub schema: String,
    pub candidate_id: String,
    pub working_intent_sha256: String,
    pub working_early_sha256: String,
    pub source_commit: String,
    pub source_tree: String,
    pub joint_policy_sha256: String,
    pub applications: BytesPin,
    pub cell: BytesPin,
    pub selection: BytesPin,
    pub normal_initrd: BytesPin,
    pub working_return_core: BytesPin,
    pub original_grub_cfg: BytesPin,
    pub original_grub_cfg_mode: u32,
    pub original_custom: BytesPin,
    pub grub_editenv: BytesPin,
    pub systemctl: BytesPin,
    pub journalctl: BytesPin,
}
impl Configuration {
    pub fn validate(&self) -> io::Result<()> {
        if self.schema != "droidloom.production-commit-source.v1"
            || ![
                &self.candidate_id,
                &self.working_intent_sha256,
                &self.working_early_sha256,
                &self.joint_policy_sha256,
            ]
            .into_iter()
            .all(|s| digest(s))
            || !commit(&self.source_commit)
            || !commit(&self.source_tree)
        {
            return Err(reject("production source is not one normal candidate"));
        }
        for p in [
            &self.applications,
            &self.cell,
            &self.selection,
            &self.working_return_core,
            &self.original_grub_cfg,
            &self.grub_editenv,
            &self.systemctl,
            &self.journalctl,
        ] {
            p.validate(128 * 1024 * 1024)?;
        }
        if self.original_custom.bytes > 1024 * 1024
            || !digest(&self.original_custom.sha256)
            || (self.original_custom.bytes == 0
                && self.original_custom.sha256
                    != "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855")
        {
            return Err(reject("original custom GRUB source differs"));
        }
        if ![0o400, 0o444, 0o600, 0o644].contains(&self.original_grub_cfg_mode) {
            return Err(reject("original GRUB configuration authority differs"));
        }
        self.normal_initrd.validate(512 * 1024 * 1024)
    }
    pub fn directory(&self) -> io::Result<PathBuf> {
        self.validate()?;
        Ok(PathBuf::from("/var/lib/droidloom/qualification")
            .join(format!("production-commit-{}", self.candidate_id)))
    }
    pub fn entry(&self) -> io::Result<String> {
        entry(&self.candidate_id)
    }
    pub fn initrd(&self) -> io::Result<PathBuf> {
        initrd(&self.candidate_id)
    }
}
pub fn entry(candidate: &str) -> io::Result<String> {
    if !digest(candidate) {
        return Err(reject("production candidate id differs"));
    }
    Ok(format!("droidloom-production-{candidate}"))
}
pub fn initrd(candidate: &str) -> io::Result<PathBuf> {
    entry(candidate)?;
    Ok(PathBuf::from("/boot/droidloom/production")
        .join(candidate)
        .join("initrd.img"))
}
pub fn ordinary_arguments(candidate: &str, config: &str) -> io::Result<String> {
    entry(candidate)?;
    if !digest(config) {
        return Err(reject("ordinary boot needs its actual whole configuration"));
    }
    Ok(format!(
        "root=UUID={} ro rootwait init=/usr/lib/droidloom/board-init lsm={LSM_ORDER} enforcing=1 selinux=1 audit=1 panic=10 systemd.wants={VERIFY_UNIT} droidloom.production={candidate} droidloom.production.source={config}",
        original::ROOT_UUID
    ))
}
pub fn ordinary_entry(candidate: &str, config: &str) -> io::Result<String> {
    let id = entry(candidate)?;
    let args = ordinary_arguments(candidate, config)?;
    Ok(format!(
        "\nmenuentry 'Droidloom production' --id '{id}' {{\n  search --no-floppy --fs-uuid --set=root {}\n  linux /boot/droidloom/kernels/{}/vmlinuz {args}\n  initrd {}\n}}\n",
        original::ROOT_UUID,
        original::KERNEL_SHA,
        initrd(candidate)?.display()
    ))
}
pub fn fields(bytes: &[u8]) -> io::Result<BTreeMap<String, String>> {
    if bytes.len() != 1024 || !bytes.starts_with(HEADER) {
        return Err(reject("complete normal GRUB block required"));
    }
    let tail = &bytes[HEADER.len()..];
    let rest = tail.strip_prefix(WARNING).unwrap_or(tail);
    let mut out = BTreeMap::new();
    let mut offset = 0;
    while offset < rest.len() && rest[offset] != b'#' {
        let n = rest[offset..]
            .iter()
            .position(|b| *b == b'\n')
            .ok_or_else(|| reject("GRUB field truncated"))?;
        let line =
            std::str::from_utf8(&rest[offset..offset + n]).map_err(|_| reject("GRUB encoding"))?;
        let (k, v) = line
            .split_once('=')
            .ok_or_else(|| reject("GRUB field unnamed"))?;
        if k.is_empty()
            || k.len() > 64
            || v.len() > 512
            || !k.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
            || !v.bytes().all(|b| (0x20..=0x7e).contains(&b))
            || out.insert(k.into(), v.into()).is_some()
        {
            return Err(reject("ambiguous GRUB field"));
        }
        offset += n + 1;
    }
    if !rest[offset..].iter().all(|b| *b == b'#') {
        return Err(reject("GRUB padding differs"));
    }
    Ok(out)
}
pub fn selected_only(before: &[u8], after: &[u8], candidate: &str, trial: bool) -> io::Result<()> {
    entry(candidate)?;
    let key = if trial { TRIAL } else { ACTIVE };
    let a = fields(before)?;
    let mut b = fields(after)?;
    if a.get(key).is_some_and(|v| !v.is_empty())
        || a.get("next_entry").is_some_and(|v| !v.is_empty())
        || a.get(if trial { ACTIVE } else { TRIAL })
            .is_some_and(|v| !v.is_empty())
        || b.remove(key).as_deref() != Some(candidate)
        || before[HEADER.len()..].starts_with(WARNING) != after[HEADER.len()..].starts_with(WARNING)
    {
        return Err(reject(
            "production selection is not the one new owned field",
        ));
    }
    let mut old = a;
    old.remove(key);
    if old != b {
        return Err(reject("production changed another actual GRUB field"));
    }
    Ok(())
}
pub fn selector(candidate: &str) -> io::Result<String> {
    let id = entry(candidate)?;
    let d = '$';
    Ok(format!(
        "\nif [ \"{d}{{boot_once}}\" != \"true\" ]; then\n  if [ \"{d}{{{TRIAL}}}\" = \"{candidate}\" ]; then\n    set default=\"{id}\"\n    set {TRIAL}=\n    save_env {TRIAL}\n  elif [ \"{d}{{{ACTIVE}}}\" = \"{candidate}\" ]; then\n    set default=\"{id}\"\n  fi\nfi\n"
    ))
}
