#[test]
fn store_rejects_symlinks_hardlink_aliases_and_permission_drift() {
    for kind in ["root", "marker", "segment", "hardlink", "permissions"] {
        let temp = Temp::new();
        let root = temp.path("store");
        two(&root);
        match kind {
            "root" => {
                fs::rename(&root, temp.path("real")).unwrap();
                symlink(temp.path("real"), &root).unwrap();
            }
            "marker" => {
                fs::rename(root.join("store.v1"), temp.path("marker")).unwrap();
                symlink(temp.path("marker"), root.join("store.v1")).unwrap();
            }
            "segment" => {
                fs::rename(segments(&root, 2), temp.path("seg")).unwrap();
                symlink(temp.path("seg"), segments(&root, 2)).unwrap();
            }
            "hardlink" => {
                fs::hard_link(segments(&root, 1), temp.path("alias")).unwrap();
            }
            _ => {
                fs::set_permissions(&root, fs::Permissions::from_mode(0o750)).unwrap();
            }
        }
        assert!(ReceiptJournal::open_managed(&root, ID, Policy::RECOVER_CRASH).is_err());
    }
}
#[test]
fn marker_replacement_or_inplace_mutation_poison_the_live_writer() {
    for replacement in [false, true] {
        let temp = Temp::new();
        let root = temp.path("store");
        let mut writer = ReceiptJournal::create_managed(&root, ID, 1).unwrap();
        let before = fs::read(writer.path()).unwrap();
        let marker = root.join("store.v1");
        let mut bytes = fs::read(&marker).unwrap();
        if replacement {
            fs::remove_file(&marker).unwrap();
        } else {
            bytes[8] ^= 1;
        }
        fs::write(&marker, bytes).unwrap();
        fs::set_permissions(&marker, fs::Permissions::from_mode(0o600)).unwrap();
        assert!(writer.append(event("one", State::Requested)).is_err());
        assert!(matches!(
            writer.append(event("two", State::Requested)),
            Err(JournalError::WriterPoisoned)
        ));
        assert_eq!(fs::read(writer.path()).unwrap(), before);
    }
}
