#[test]
fn automatic_rotation_trigger_waits_for_terminal_facts_and_resets_after_commit() {
    let temp = Temp::new();
    let root = temp.path("store");
    let mut writer = ReceiptJournal::create_managed(&root, ID, 1).unwrap();
    assert!(!writer.managed_rotation_due());
    let mut count = 0;
    while !writer.managed_rotation_due() {
        count += 1;
        assert!(count < 2000);
        for state in [State::Requested, State::Interrupted] {
            let mut value = event(&format!("size-{count}"), state);
            value.detail = Some("x".repeat(4096));
            writer.append(value).unwrap();
        }
    }
    writer.append(event("inflight", State::Requested)).unwrap();
    assert!(!writer.managed_rotation_due());
    writer
        .append(event("inflight", State::Interrupted))
        .unwrap();
    assert!(writer.managed_rotation_due());
    let (_, mut writer) = writer.rotate_managed(3).unwrap();
    assert!(!writer.managed_rotation_due());
    assert!(writer.append(event("size-1", State::Requested)).is_err());
}
