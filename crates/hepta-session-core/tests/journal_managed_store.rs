fn complete(writer: &mut ReceiptJournal, id: &str) {
    writer.append(event(id, State::Requested)).unwrap();
    writer.append(event(id, State::Interrupted)).unwrap();
}
fn open(root: &Path) -> ReceiptJournal {
    ReceiptJournal::open_managed(root, ID, Policy::STRICT).unwrap()
}
fn segments(root: &Path, n: usize) -> std::path::PathBuf {
    root.join(format!("segment-{n:016}.journal"))
}
fn two(root: &Path) {
    let mut writer = ReceiptJournal::create_managed(root, ID, 1).unwrap();
    complete(&mut writer, "first");
    let (_, mut next) = writer.rotate_managed(2).unwrap();
    complete(&mut next, "second");
}
fn prepared(root: &Path) {
    let mut writer = ReceiptJournal::create_managed(root, ID, 1).unwrap();
    complete(&mut writer, "first");
    let (_, next) = writer.rotate_managed(2).unwrap();
    drop(next);
    // Construct the precise durable pre-publication state using a real linked
    // header generated by rotate, without inserting faults in the product.
    fs::rename(segments(root, 2), root.join("next.pending")).unwrap();
}

#[test]
fn managed_reopen_selects_latest_head_and_all_receipt_ids() {
    let temp = Temp::new();
    let root = temp.path("store");
    two(&root);
    let mut writer = open(&root);
    assert!(writer.is_managed());
    assert_eq!(writer.path(), segments(&root, 2));
    let before = fs::read(writer.path()).unwrap();
    for id in ["first", "second"] {
        assert!(writer.append(event(id, State::Requested)).is_err());
    }
    assert_eq!(fs::read(writer.path()).unwrap(), before);
    assert_eq!(
        writer
            .append(event("third", State::Requested))
            .unwrap()
            .sequence,
        5
    );
}
#[test]
fn managed_store_cannot_downgrade_to_any_unmanaged_writer_api() {
    let temp = Temp::new();
    let root = temp.path("store");
    two(&root);
    let first = segments(&root, 1);
    let last = segments(&root, 2);
    assert!(ReceiptJournal::open(&first, JournalOpenPolicy::RECOVER_CRASH).is_err());
    assert!(ReceiptJournal::open_chain([&first], ID, JournalOpenPolicy::STRICT).is_err());
    assert!(ReceiptJournal::open_chain([&first, &last], ID, JournalOpenPolicy::STRICT).is_err());
    assert!(ReceiptJournal::create(root.join("new"), ID, 1).is_err());
    let writer = open(&root);
    assert!(writer.rotate(root.join("new"), 3).is_err());
    assert!(!root.join("new").exists());
    assert_eq!(fs::read_dir(&root).unwrap().count(), 3);
}
#[test]
fn pending_header_requires_explicit_recovery_and_preserves_chain() {
    let temp = Temp::new();
    let root = temp.path("store");
    prepared(&root);
    let before = fs::read(segments(&root, 1)).unwrap();
    let pending = fs::read(root.join("next.pending")).unwrap();
    assert!(ReceiptJournal::open_managed(&root, ID, Policy::STRICT).is_err());
    assert_eq!(fs::read(root.join("next.pending")).unwrap(), pending);
    let mut writer = ReceiptJournal::open_managed(&root, ID, Policy::RECOVER_CRASH).unwrap();
    assert_eq!(writer.path(), segments(&root, 2));
    assert!(!root.join("next.pending").exists());
    assert_eq!(fs::read(segments(&root, 2)).unwrap(), pending);
    assert_eq!(fs::read(segments(&root, 1)).unwrap(), before);
    assert!(writer.append(event("first", State::Requested)).is_err());
    assert_eq!(
        writer
            .append(event("new", State::Requested))
            .unwrap()
            .sequence,
        3
    );
}
