    #[test]
    #[ignore = "root/ext4 private fixture only; never opens the live GRUB environment"]
    fn fresh_grub_actual_normal_unset_preserves_boot_fields_and_same_inode() {
        use std::{os::unix::fs::PermissionsExt, process::Command};
        assert_eq!(rustix::process::geteuid().as_raw(), 0);
        let root = tempfile::Builder::new()
            .prefix(".p4-return-grub-private-")
            .tempdir_in(std::env::current_dir().unwrap())
            .unwrap();
        let path = root.path().join("grubenv");
        let execute = |args: &[&str]| {
            assert!(
                Command::new(TOOL)
                    .arg(&path)
                    .args(args)
                    .status()
                    .unwrap()
                    .success()
            );
        };
        execute(&["create"]);
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o644)).unwrap();
        let tool = ProtectedFile::open(
            &files::pin_file(Path::new(TOOL)).unwrap(),
            &[0o755],
            16 * 1024 * 1024,
        )
        .unwrap();
        for (index, entry) in [
            candidate_entry(CANDIDATE).unwrap(),
            c::ORIGINAL_ENTRY.to_owned(),
        ]
        .iter()
        .enumerate()
        {
            execute(&[
                "set",
                "saved_entry=current-original",
                "recordfail=1",
                "boot_success=0",
                &format!("next_entry={entry}"),
            ]);
            let file = File::open(&path).unwrap();
            let before = Environment::capture(&file).unwrap();
            assert!(owned_selection(&before.bytes, CANDIDATE).unwrap());
            let work = root.path().join(format!("unset-{index}"));
            files::private_dir(&work).unwrap();
            let actual = unset_owned(&work, &tool, &file).unwrap();
            assert_eq!(actual["owned_pidfd_retired"], true);
            assert_eq!(actual["acknowledged"], true);
            file.sync_all().unwrap();
            rustix::fs::syncfs(&file).unwrap();
            let after = Environment::capture(&file).unwrap();
            before.same_inode(&after).unwrap();
            cleared_only(&before.bytes, &after.bytes, CANDIDATE).unwrap();
            assert_eq!(
                after,
                Environment::capture(&File::open(&path).unwrap()).unwrap()
            );
            let values = fields(&after.bytes).unwrap();
            assert_eq!(values["recordfail"], "1");
            assert_eq!(values["boot_success"], "0");
        }
    }
