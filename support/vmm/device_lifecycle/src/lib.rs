//! Device/queue/buffer *state transition model*, not a GPU driver or security authority.
//!
//! `#![no_std]` and no allocator: this logic can be reviewed for eventual Asterinas
//! integration, but it does not perform HOS2 authentication, canonical budget
//! installation, MMIO, IOMMU mapping, cache maintenance, IRQ acknowledgement,
//! or hardware reset. It does contain a metadata-only resource admission mirror
//! so A06 can review the accounting and unknown-effect rules before integration.
//! Only the canonical A05/A06 kernel owners may call these transitions after
//! their real platform preconditions have completed. A forged `Completion` or
//! externally asserted quiescence is NOT a physical completion proof.
#![no_std]
#![forbid(unsafe_code)]

/// A value-only *mirror* of the canonical 16-byte HOS2 ResourceDomainId.
///
/// This is NOT the A03/A05/A06 kernel identity type, nor a capability.
/// The authoritative kernel owner must convert/validate the full 16 bytes;
/// no truncation to a u64 or additional GPU identity namespace is allowed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ResourceDomainId([u8; 16]);

impl ResourceDomainId {
    pub const fn new(bytes: [u8; 16]) -> Self {
        Self(bytes)
    }
    pub const fn from_u128(value: u128) -> Self {
        Self(value.to_be_bytes())
    }
    pub const fn bytes(self) -> [u8; 16] {
        self.0
    }
    pub const fn is_nonzero(self) -> bool {
        let mut i = 0;
        while i < self.0.len() {
            if self.0[i] != 0 {
                return true;
            }
            i += 1;
        }
        false
    }
}

// Device binding is only an identity check, not a device capability.
// The canonical A05 PCI registry must still reject independent duplicate handles.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct DeviceIdentity {
    pci_bdf: u32,
    iommu_group: u32,
    instance_id: u64,
}

/// State-only handle to an exclusive physical device's entire IOMMU group.
/// instance_id is a per-attach lifetime identity supplied by A05's trusted
/// device registry, not a permission token and not generated by this crate.
/// Intentionally not Clone or Copy; the real kernel still needs one authoritative registry.
#[derive(Debug, PartialEq, Eq)]
pub struct DeviceHandle {
    pci_bdf: u32,
    iommu_group: u32,
    instance_id: u64,
    generation: u64,
    state: DeviceState,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DeviceState {
    Unassigned,
    Assigned(ResourceDomainId),
    Fenced,
    Quarantined,
}

