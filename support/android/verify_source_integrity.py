PARSED_SUFFIXES = {".py", ".sh", ".json", ".xml"}


def check_sources(root: Path = ROOT) -> dict:
    root = Path(root).resolve()
    errors = []
    paths = set(REQUIRED_FILES)
    for directory in SOURCE_ROOTS:
        for path in (root / directory).rglob("*"):
            relative = path.relative_to(root)
            if {"evidence", "__pycache__"} & set(relative.parts):
                continue
            if path.is_file() and path.suffix in PARSED_SUFFIXES:
                paths.add(relative.as_posix())
    checked = 0

    def error(path, stage, detail):
        errors.append({"path": path, "stage": stage, "error": str(detail)})

    for relative in sorted(paths):
        path = root / relative
        if not path.is_file():
            error(relative, "presence", "required source file is missing")
            continue
        if not path.resolve().is_relative_to(root):
            error(relative, "presence", "source path escapes the checkout")
            continue
        checked += 1
        try:
            text = path.read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            error(relative, "utf8", exc)
            continue
        if not text.strip():
            error(relative, "content", "required source file is empty")
            continue
        if relative in EXECUTABLE_FILES and not path.stat().st_mode & 0o111:
            error(relative, "mode", "shell entry point lost its executable mode")
        try:
            if path.suffix == ".py":
                compile(text, relative, "exec")
            elif path.suffix == ".json":
                json.loads(text)
            elif path.suffix == ".xml":
                ET.fromstring(text)
            elif path.suffix == ".sh":
                # bash -n accepts one script; remaining argv are script arguments.
                result = subprocess.run(
                    ["bash", "-n", str(path)], cwd=root, capture_output=True,
                    text=True, errors="replace", timeout=10, check=False,
                )
                if result.returncode:
                    error(relative, "syntax", result.stderr.strip())
        except (SyntaxError, ValueError, ET.ParseError, OSError,
                subprocess.TimeoutExpired) as exc:
            error(relative, "syntax", exc)

    return {
        "schema": 1,
        "scope": "A08_SOURCE_INTEGRITY_ONLY",
        "status": "source_integrity_failed" if errors else "source_integrity_passed",
        "required_files": len(REQUIRED_FILES),
        "checked_files": checked,
        "errors": errors,
        "android_on_asterinas_verified": False,
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)
    report = check_sources(args.root)
    rendered = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(rendered, encoding="utf-8")
    print(rendered, end="")
    return 1 if report["errors"] else 0


if __name__ == "__main__":
    sys.exit(main())

