use rand::{RngCore, SeedableRng, rngs::StdRng};
use spin::Once;

use crate::prelude::*;

// Publish the generator and its immutable seed provenance together. No caller
// can promote a diagnostic generator or replace its provenance independently.
static RNG: Once<(SpinLock<StdRng>, SeedSource)> = Once::new();

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum SeedSource {
    Hardware,
    #[cfg(any(not(target_arch = "x86_64"), ktest))]
    DeviceTree,
    Timestamp,
}

/// Fill `dest` with random bytes.
///
/// Uses [`rand::rngs::StdRng`], whose cryptographic security requires an
/// unpredictable seed. The upstream timestamp fallback remains available for
/// diagnostic boots; it must not qualify a trusted G2 startup.
pub(crate) fn getrandom(dst: &mut [u8]) {
    RNG.get().unwrap().0.lock().fill_bytes(dst);
}

pub(crate) fn init() {
    RNG.call_once(|| {
        let (seed, source) = get_random_seed();
        (SpinLock::new(StdRng::from_seed(seed)), source)
    });
}

/// Checks the original RNG before G2 creates any trusted process or identity.
///
/// Only a complete seed from the supported hardware interface qualifies. A
/// device-tree property alone has no reviewed freshness/provider contract for
/// this profile. Diagnostic fallback, uninitialized state and that unqualified
/// bootloader seed all fail closed; this check does not collect or reseed entropy.
#[cfg(any(feature = "g2-trusted-daemon", ktest))]
pub(crate) fn require_trusted_entropy() -> Result<()> {
    check_trusted_seed(RNG.get().map(|rng| rng.1))
}

#[cfg(any(feature = "g2-trusted-daemon", ktest))]
fn check_trusted_seed(source: Option<SeedSource>) -> Result<()> {
    if source != Some(SeedSource::Hardware) {
        return_errno_with_message!(Errno::EAGAIN, "trusted hardware entropy is not ready");
    }
    Ok(())
}

fn get_random_seed() -> (<StdRng as SeedableRng>::Seed, SeedSource) {
    // Prefer the hardware RNG if available.
    if let Some(seed) = read_seed_from_hardware() {
        ostd::info!("use randomness generated by hardware");
        return (seed, SeedSource::Hardware);
    }

    // x86_64: if no hardware RNG and running inside TDX, abort.
    //
    // For more details, see
    // <https://intel.github.io/ccc-linux-guest-hardening-docs/security-spec.html#randomness-inside-tdx-guest>.
    #[cfg(target_arch = "x86_64")]
    ostd::if_tdx_enabled!({
        panic!("hardware randomness is mandatory for TD guests");
    });

    // Non-x86_64: fall back to the device-tree seed if present.
    #[cfg(not(target_arch = "x86_64"))]
    if let Some(seed) = read_seed_from_device_tree() {
        ostd::info!("use randomness provided by the device tree");
        return (seed, SeedSource::DeviceTree);
    }

    // Some platforms (e.g., RISC-V `sifive_u`) have neither hardware
    // randomness nor randomness from the device tree. For now, we will
    // continue with pseudorandomness.
    // TODO: Collect entropy from environment noise for better security.
    ostd::warn!("use randomness based on the timestamp, which is insecure");
    (read_seed_from_timestamp(), SeedSource::Timestamp)
}

fn read_seed_from_hardware() -> Option<<StdRng as SeedableRng>::Seed> {
    use ostd::arch::read_random;

    read_seed_from(read_random)
}

#[cfg(not(target_arch = "x86_64"))]
fn read_seed_from_device_tree() -> Option<<StdRng as SeedableRng>::Seed> {
    use ostd::arch::boot::DEVICE_TREE;

    DEVICE_TREE
        .get()
        .unwrap()
        .find_node("/chosen")
        .and_then(|chosen| chosen.property("rng-seed"))
        .and_then(|rng_seed| <StdRng as SeedableRng>::Seed::try_from(rng_seed.value).ok())
}

fn read_seed_from_timestamp() -> <StdRng as SeedableRng>::Seed {
    use ostd::arch::read_tsc;

    read_seed_from(|| Some(read_tsc())).unwrap()
}

fn read_seed_from(
    mut next_random: impl FnMut() -> Option<u64>,
) -> Option<<StdRng as SeedableRng>::Seed> {
    let mut seed = <StdRng as SeedableRng>::Seed::default();

    let (chunks, tail) = seed.as_mut().as_chunks_mut::<{ size_of::<u64>() }>();
    for chunk in chunks {
        let val = next_random()?;
        chunk.copy_from_slice(&val.to_ne_bytes());
    }
    if !tail.is_empty() {
        let val = next_random()?;
        tail.copy_from_slice(&val.to_ne_bytes()[..tail.len()]);
    }

    Some(seed)
}

#[cfg(ktest)]
mod tests {
    use ostd::prelude::*;

    use super::*;

    #[ktest]
    fn trusted_entropy_requires_original_initialized_hardware_seed() {
        // Audit closure: StdRng's algorithm is not proof that its seed was
        // secure. Neither a diagnostic fallback nor a firmware label qualifies.
        for source in [
            None,
            Some(SeedSource::Timestamp),
            Some(SeedSource::DeviceTree),
        ] {
            assert_eq!(check_trusted_seed(source).unwrap_err().error(), Errno::EAGAIN);
        }
        check_trusted_seed(Some(SeedSource::Hardware)).unwrap();

        // The public check observes the sole initialized owner; tests cannot
        // inject a trusted marker into that owner or replace its generator.
        init();
        let source = RNG.get().unwrap().1;
        assert_eq!(
            require_trusted_entropy().is_ok(),
            source == SeedSource::Hardware
        );
        init();
        assert_eq!(RNG.get().unwrap().1, source);
    }

    #[ktest]
    fn entropy_seed_requires_every_word_before_publication() {
        let words = size_of::<<StdRng as SeedableRng>::Seed>().div_ceil(size_of::<u64>());
        for failed_word in 0..words {
            let mut calls = 0;
            let seed = read_seed_from(|| {
                let current = calls;
                calls += 1;
                (current != failed_word).then_some(0x1234_5678_9abc_def0)
            });
            assert!(seed.is_none());
            assert_eq!(calls, failed_word + 1);
        }
        let mut calls = 0;
        let seed = read_seed_from(|| {
            calls += 1;
            Some(0x1234_5678_9abc_def0)
        })
        .unwrap();
        assert_eq!(calls, words);
        let expected = 0x1234_5678_9abc_def0u64.to_ne_bytes();
        for (index, byte) in seed.iter().enumerate() {
            assert_eq!(*byte, expected[index % expected.len()]);
        }
    }
}
